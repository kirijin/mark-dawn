"""Generate golden PDF fixtures for the conversion pipeline.

Writes tests/golden/inputs/*.pdf and the matching tests/golden/expected/*.md.
Run after changing mdclean or the conversion handlers:

    python3 tests/make_golden_fixtures.py

The PDFs are built with a digital text layer so they exercise the pymupdf4llm
path; the OCR path is covered by the unit suite (no ONNX download in CI).
"""
import sys
from pathlib import Path

GOLDEN = Path(__file__).resolve().parent / "golden"
INPUTS = GOLDEN / "inputs"
EXPECTED = GOLDEN / "expected"

HEADER = "Journal of Document Engineering"
FOOTER = "Vol. 12, No. 3"


def _paragraph(pymupdf, page, text, y, size=10, font="helv"):
    page.insert_text((72, y), text, fontsize=size, fontname=font)


def build_book(path: Path):
    """A 5-page book-like PDF: running header, footer page numbers, wrapped
    paragraphs, a chapter heading, and a caption line."""
    import pymupdf

    doc = pymupdf.open()
    chapters = [
        ("Introduction", [
            "Document conversion pipelines lose structure at every stage,",
            "and the loss is rarely visible until retrieval quality drops.",
            "This chapter states the problem in terms a maintainer can test.",
        ]),
        ("Method", [
            "We normalise the document in six deterministic stages, each of",
            "which is independently testable and free of model inference.",
            "Page boundaries survive as HTML comments rather than headings,",
            "so the heading tree reflects the document's own ontology.",
        ]),
        ("Results", [
            "Running headers and footers are detected by repetition across",
            "pages, then removed before paragraph reconstruction runs.",
            "Hard-wrapped lines are joined into semantic paragraphs.",
        ]),
        ("Discussion", [
            "The gate reports findings as codes, not prose, so a CI job can",
            "fail on structure without failing on style.",
            "Figure 1  Pipeline stages and their failure modes.",
        ]),
    ]

    page_no = 1
    for title, lines in chapters:
        page = doc.new_page()
        y = 60
        _paragraph(pymupdf, page, HEADER, 30, size=8)
        page.insert_text((72, y + 12), title, fontsize=16, fontname="hebo")
        y += 40
        for line in lines:
            if line.startswith("Figure"):
                page.insert_text((72, y), line, fontsize=9, fontname="heit")
            else:
                _paragraph(pymupdf, page, line, y)
            y += 14
        page.insert_text((72, 780), str(page_no), fontsize=8, fontname="helv")
        page.insert_text((200, 780), FOOTER, fontsize=8, fontname="helv")
        page_no += 1

    # A second copy of the first chapter's body on later pages makes the
    # repetition detector fire without hand-editing expected output.
    doc.save(str(path))
    doc.close()


def main():
    try:
        import pymupdf
    except ImportError:
        print("pymupdf not installed; skipping fixture generation", file=sys.stderr)
        return 1

    INPUTS.mkdir(parents=True, exist_ok=True)
    EXPECTED.mkdir(parents=True, exist_ok=True)

    book = INPUTS / "book.pdf"
    build_book(book)
    print(f"wrote {book}")

    # Expected output is generated by the real pipeline so the fixture cannot
    # drift from behaviour. Review the diff when mdclean changes.
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    import mdclean
    import convert_pdf

    md = convert_pdf._pdf_markdown(book)

    expected = mdclean.clean(md, title="book")
    (EXPECTED / "book.md").write_text(expected, encoding="utf-8")
    print(f"wrote {EXPECTED / 'book.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())